-- ─── Functions ──────────────────────────────────────────────────────────────
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path to '' as $$
begin
  insert into public.profiles (id, first_name, last_name)
  values (new.id, new.raw_user_meta_data ->> 'first_name', new.raw_user_meta_data ->> 'last_name');
  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.create_group(group_name text)
returns uuid language plpgsql security definer as $$
declare
  new_id uuid;
  new_code text;
begin
  new_code := upper(substring(md5(random()::text) from 1 for 6));
  insert into public.groups (name, share_code, created_by) values (group_name, new_code, auth.uid()) returning id into new_id;
  insert into public.group_members (group_id, user_id) values (new_id, auth.uid());
  return new_id;
end;
$$;

create or replace function public.join_group(invite_code text)
returns void language plpgsql security definer as $$
declare
  target_group_id uuid;
begin
  select id into target_group_id from public.groups where share_code = invite_code;
  if target_group_id is null then
    raise exception 'Invalid share code. Please double check with your friend!';
  end if;
  insert into public.group_members (group_id, user_id) values (target_group_id, auth.uid()) on conflict do nothing;
end;
$$;

create or replace function public.delete_user_account()
returns void language plpgsql security definer as $$
begin
  delete from auth.users where id = auth.uid();
end;
$$;

create or replace function public.check_and_update_visited_status(p_restaurant_id integer)
returns boolean language plpgsql security definer as $$
declare
  v_group_id uuid; v_place_id text; v_member_count int; v_review_count int; v_consensus boolean;
begin
  select group_id, place_id into v_group_id, v_place_id from public.restaurants where id = p_restaurant_id;
  if v_group_id is null then
    update public.restaurants set visited = true where id = p_restaurant_id;
    return true;
  end if;
  select count(distinct user_id) into v_member_count from public.group_members where group_id = v_group_id;
  select count(distinct r.user_id) into v_review_count from public.reviews r
    join public.group_members gm on r.user_id = gm.user_id
    where r.place_id = v_place_id and gm.group_id = v_group_id;
  v_consensus := v_member_count > 0 and v_review_count >= v_member_count;
  update public.restaurants set visited = v_consensus where id = p_restaurant_id;
  return v_consensus;
end;
$$;

create or replace function public.get_random_restaurant(p_group_id uuid default null)
returns setof public.restaurants language plpgsql as $$
begin
  if p_group_id is not null then
    return query select * from public.restaurants where group_id = p_group_id order by random() limit 1;
  else
    return query select * from public.restaurants order by random() limit 1;
  end if;
end;
$$;


-- ─── Tables ─────────────────────────────────────────────────────────────────
create table public.profiles (
  id uuid not null,
  created_at timestamp with time zone default now(),
  first_name text,
  last_name text,
  avatar_url text,
  constraint profiles_pkey primary key (id),
  constraint profiles_id_fkey foreign key (id) references auth.users(id) on delete cascade
);

create table public.groups (
  id uuid default gen_random_uuid() not null,
  name text not null,
  share_code text,
  created_by uuid,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  avatar_url text,
  constraint groups_pkey primary key (id),
  constraint groups_share_code_key unique (share_code),
  constraint groups_created_by_fkey foreign key (created_by) references auth.users(id) on delete cascade
);

create table public.group_members (
  group_id uuid not null,
  user_id uuid not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  constraint group_members_pkey primary key (group_id, user_id),
  constraint group_members_group_id_fkey foreign key (group_id) references public.groups(id) on delete cascade,
  constraint group_members_user_id_fkey foreign key (user_id) references public.profiles(id) on delete cascade
);

create sequence public.restaurants_id_seq;
create table public.restaurants (
  id integer default nextval('restaurants_id_seq'::regclass) not null,
  owner text not null,
  place_id text not null,
  name text not null,
  address text not null,
  latitude text not null,
  longitude text not null,
  rating text,
  user_rating_count integer,
  price_level text,
  primary_type text,
  photo_url text,
  website_url text,
  booking_platform text,
  booking_url text,
  vibes text default '[]'::text not null,
  notes text default ''::text,
  visited boolean default false not null,
  user_score integer,
  visit_photo_url text,
  visited_at timestamp with time zone,
  created_at timestamp with time zone default now() not null,
  group_id uuid not null,
  opening_hours jsonb,
  last_synced_at timestamp with time zone default now(),
  constraint restaurants_pkey primary key (id),
  constraint restaurants_group_id_fkey foreign key (group_id) references public.groups(id) on delete cascade
);
alter sequence public.restaurants_id_seq owned by public.restaurants.id;

create table public.reviews (
  id bigint generated by default as identity not null,
  user_id uuid not null,
  score integer,
  notes text,
  photo_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  photo_urls text[] default '{}'::text[],
  place_id character varying(255) not null,
  constraint reviews_pkey primary key (id),
  constraint reviews_user_id_fkey foreign key (user_id) references auth.users(id)
);
create index idx_reviews_place_id on public.reviews using btree (place_id);

